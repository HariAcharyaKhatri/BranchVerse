/**
 * Helper to find definition by ID or name
 */
export function findPowerDefinition(query: string): PowerDefinition | undefined {
  const q = query.trim().toLowerCase();
  return ALL_POWER_DEFINITIONS.find(
    (p) => p.id.toLowerCase() === q || p.name.toLowerCase().includes(q)
  );
}

/**
 * Filter catalogue by category, search text, or combat/non-combat
 */
export function filterPowerCatalogue(params: {
  category?: TalentCategory | 'all';
  searchQuery?: string;
  query?: string;
  isCombatOnly?: boolean;
  combatFilter?: 'all' | 'combat' | 'non_combat';
  tierFilter?: PowerTierCode | 'all';
}): PowerDefinition[] {
  const effectiveQuery = (params.query ?? params.searchQuery ?? '').toLowerCase().trim();
  const isCombatFilter =
    params.combatFilter === 'combat'
      ? true
      : params.combatFilter === 'non_combat'
      ? false
      : params.isCombatOnly;

  return ALL_POWER_DEFINITIONS.filter((p) => {
    if (params.category && params.category !== 'all' && p.category !== params.category) {
      return false;
    }
    if (isCombatFilter !== undefined && p.isCombat !== isCombatFilter) {
      return false;
    }
    if (params.tierFilter && params.tierFilter !== 'all' && p.defaultTier !== params.tierFilter) {
      return false;
    }
    if (effectiveQuery) {
      const matchName = p.name.toLowerCase().includes(effectiveQuery);
      const matchDesc = p.description.toLowerCase().includes(effectiveQuery);
      const matchSpecs = p.specializations?.some((s) => s.toLowerCase().includes(effectiveQuery));
      const matchApps = p.applications?.some((a) => a.toLowerCase().includes(effectiveQuery));
      if (!matchName && !matchDesc && !matchSpecs && !matchApps) return false;
    }
    return true;
  });
}
